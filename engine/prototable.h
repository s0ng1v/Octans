enum {
    PROTO_F_NONE         = 0,
    PROTO_F_DRAIN_FIRST  = 1u << 0,
    PROTO_F_WIRED        = 1u << 1,
    PROTO_F_RETRY2       = 1u << 2,
    PROTO_F_PASSIVE_ONLY = 1u << 3
};

typedef struct proto_entry {
    const wchar_t *brand;
    const wchar_t *name;
    uint16_t vid;
    uint16_t pid;          /**< 0xFFFF = wildcard PID */
    uint16_t usage_page;   /**< 0 = any */
    uint16_t usage;        /**< 0 = any */
    int16_t interface_num; /**< -1 = any */
    octans_device_kind_t kind;
    octans_conn_kind_t conn;
    octans_family_t family;
    octans_proto_variant_t variant;
    octans_tx_kind_t tx;
    uint8_t report_id;
    uint8_t req_len;
    uint8_t reply_head;
    uint8_t curve_id;
    uint16_t flags;
} proto_entry_t;

/* Compile-time protocol row encoder (obfuscates VID/PID/usage/report IDs in .rdata). */
#define OCTANS_PROTO(brand, name, vid, pid, up, u, mi, kind, conn, fam, var, tx, rid, rlen, rhead, curve, flags) \
    { (brand), (name), \
      OCTANS_ENC16((vid), 1u), OCTANS_ENC16((pid), 2u), \
      OCTANS_ENC16((up), 3u), OCTANS_ENC16((u), 4u), \
      (mi), (kind), (conn), (fam), (var), (tx), \
      OCTANS_ENC8((rid), 5u), OCTANS_ENC8((rlen), 6u), OCTANS_ENC8((rhead), 7u), \
      (curve), (flags) }

